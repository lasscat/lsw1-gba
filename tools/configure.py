#!/usr/bin/env python3
"""Writes build.ninja for the LSW1 GBA ROM: asm objects in ROM order, with C objects swapped in.

    python tools/configure.py [--binutils-prefix arm-none-eabi-]
    ninja                 # disasm emit (when its inputs change) -> as / cc -> ld -> objcopy
    ninja verify          # the build, then tools/verify.py

asm/ is generated by `tools/disasm.py emit` from the user's ROM; the object list is asm/manifest.txt in ROM order.
config/usa/sources.txt lists the C files that replace asm functions (tools/project.py read_sources): each C object
takes the link position of its first function, and those functions' asm files leave the link. Labels the swapped asm
exported for other files (Thumb aliases `_XXXXXXXX`) and `data` symbols outside the segments are defined in a
generated linker script, build/usa/c_symbols.ld. build.ninja depends on the manifest and sources.txt, so ninja
re-runs the disassembler and then this script when needed. All paths and flags: tools/project.py.
"""
import argparse
import json
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import project  # noqa: E402  (every path and flag: tools/project.py)
import ninja_syntax  # noqa: E402

ROOT = project.ROOT
rel = project.rel


def plan_link(manifest_lines: list, sources: list):
    """(link list of ("asm" | "c", path), alias definitions) after the sources.txt swaps."""
    files = [line.split(None, 1) for line in manifest_lines if line.strip()]
    index = {path: i for i, (_seg, path) in enumerate(files)}
    syms = {name: a for a, (kind, name) in project.read_symbols().items()}
    swap_at, dropped, aliases = {}, set(), []
    for c, names in sources:
        if not (ROOT / c).is_file():
            raise SystemExit(f'configure: {c} (sources.txt) does not exist')
        pos = []
        for name in names:
            path = f'code/{name}.s'
            if name not in syms or path not in index:
                raise SystemExit(f'configure: {c}: {name} is not a function of asm/manifest.txt')
            if path in dropped:
                raise SystemExit(f'configure: {name} is claimed by two sources.txt lines')
            i = index[path]
            if files[i][0] != 'rom':
                raise SystemExit(f'configure: {name} is in {files[i][0]}; only ROM (.text) functions can be C yet')
            pos.append(i)
            dropped.add(path)
            for label in exported_labels(project.ASM / path):
                if label == name:
                    continue
                if label != f'_{syms[name]:08X}':
                    raise SystemExit(f'configure: {name} cannot move to C: other files use its label {label}')
                aliases.append(f'{label} = {name};')
        if pos != list(range(pos[0], pos[0] + len(pos))):
            raise SystemExit(f'configure: {c}: functions must be listed contiguous and in ROM order')
        if syms[names[0]] % 4:
            raise SystemExit(f'configure: {names[0]} is not 4-aligned; agbcc objects start 4-aligned')
        swap_at[pos[0]] = c
    link = []
    for i, (_seg, path) in enumerate(files):
        if i in swap_at:
            link.append(('c', swap_at[i]))
        elif path not in dropped:
            link.append(('asm', path))
    return link, aliases


def exported_labels(asm: Path) -> list:
    return [line.split()[1] for line in asm.read_text().splitlines()
            if line.startswith('\t.global ') or line.startswith('\tthumb_func_start ')
            or line.startswith('\tarm_func_start ')]


def data_defs() -> list:
    """Absolute definitions for symbols.txt `data` names outside every segment (RAM the asm only reaches by
    address), so C can name them."""
    return [f'{name} = 0x{a:08X};' for a, (kind, name) in sorted(project.read_symbols().items())
            if kind == 'data' and not project.in_segment(a)]


def objdiff_units(manifest_lines: list, sources: list) -> tuple:
    """objdiff.json units, one per code/ function: its asm object is the target, its C object (sources.txt) the
    base. Returns (units, asm paths that need a target-only build because the ROM links their C instead)."""
    c_of = {name: c for c, names in sources for name in names}
    addr_of = {name: a for a, (kind, name) in project.read_symbols().items()}
    units, target_only = [], []
    for seg, path in (line.split(None, 1) for line in manifest_lines if line.strip()):
        if not path.startswith('code/'):
            continue
        name = Path(path).stem
        game = project.GAME_CODE[0] <= addr_of[name] < project.GAME_CODE[1]
        category = 'game' if game else 'lib'
        unit = {'name': f'{category}/{name}', 'target_path': rel(project.asm_object(name)),
                'metadata': {'progress_categories': [category], 'complete': name in c_of}}
        if name in c_of:
            unit['base_path'] = rel(project.OBJ / 'c' / Path(c_of[name]).with_suffix('.o'))
            unit['metadata']['source_path'] = c_of[name]
            target_only.append(path)
        units.append(unit)
    return units, target_only


def objdiff_config(units: list) -> dict:
    return {
        '$schema': 'https://raw.githubusercontent.com/encounter/objdiff/main/config.schema.json',
        'custom_make': 'ninja',
        'build_target': False,
        'build_base': True,
        'watch_patterns': ['*.c', '*.h', '*.s', '*.inc'],
        'progress_categories': [{'id': 'game', 'name': 'Game code'},
                                {'id': 'lib', 'name': 'Libraries (SDK, libgcc, Krawall)'}],
        'units': units,
    }


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('--binutils-prefix', default='arm-none-eabi-', help='GNU binutils prefix (default: %(default)s)')
    ap.add_argument('--python', default=sys.executable, help='Python for the tools (default: this one)')
    ap.add_argument('--objdiff', default='./objdiff-cli', help='objdiff CLI for `ninja report` (default: %(default)s)')
    args = ap.parse_args()

    tools = {t: args.binutils_prefix + t for t in ('as', 'ld', 'objcopy')}
    for t in tools.values():
        if shutil.which(t) is None:
            raise SystemExit(f'configure: {t} not found on PATH (install arm-none-eabi binutils)')
    sources = project.read_sources()
    if sources:
        for t in (project.CPP, str(project.CC)):
            if shutil.which(t) is None:
                raise SystemExit(f'configure: {t} not found (clang on PATH; agbcc from tools/setup_agbcc.sh)')
    baserom = project.find_baserom()  # fails early without the user's dump
    py = args.python

    manifest = project.MANIFEST
    if not manifest.is_file():
        print('configure: asm/manifest.txt missing; running tools/disasm.py emit')
        import subprocess
        subprocess.run([py, str(ROOT / 'tools' / 'disasm.py'), 'emit'], check=True, cwd=ROOT)
    link, aliases = plan_link(manifest.read_text().splitlines(), sources)
    units, target_only = objdiff_units(manifest.read_text().splitlines(), sources)

    obj = project.OBJ
    elf = project.ELF
    rom = project.BUILT_ROM
    c_symbols = project.BUILD / 'c_symbols.ld'
    defs = aliases + data_defs()
    c_symbols.parent.mkdir(parents=True, exist_ok=True)
    # Written every run: it is an output of the configure edge, so it must not stay older than that edge's inputs.
    c_symbols.write_text('/* Generated by tools/configure.py: symbols the C objects need. */\n'
                         + ''.join(d + '\n' for d in defs))
    objdiff_json = ROOT / 'objdiff.json'  # untracked; regenerated like c_symbols.ld
    objdiff_json.write_text(json.dumps(objdiff_config(units), indent=2) + '\n')

    with open(ROOT / 'build.ninja', 'w') as fh:
        n = ninja_syntax.Writer(fh, width=120)
        n.comment('Generated by tools/configure.py; do not edit.')
        n.variable('ninja_required_version', '1.10')
        n.variable('python', py)
        n.variable('as', tools['as'])
        n.variable('ld', tools['ld'])
        n.variable('objcopy', tools['objcopy'])
        n.variable('asflags', ' '.join(project.AS_FLAGS) + ' -I asm')
        n.variable('cpp', project.CPP)
        n.variable('cppflags', ' '.join(project.CPP_ARGS))
        n.variable('cc', rel(project.CC) if project.CC.is_relative_to(ROOT) else str(project.CC))
        n.variable('ccflags', ' '.join(project.CC_FLAGS))
        n.variable('objdiff', args.objdiff)
        n.newline()

        n.rule('configure', '$python tools/configure.py --binutils-prefix ' + args.binutils_prefix
               + ' --python $python --objdiff $objdiff', description='CONFIGURE', generator=True)
        n.rule('disasm', '$python tools/disasm.py emit', description='DISASM asm/', restat=True)
        n.rule('as', '$as $asflags --MD $out.d -o $out $in', description='AS $in', depfile='$out.d', deps='gcc')
        # The same steps as project.compile_c (the judge), END_PAD included; .i and .s stay next to the object.
        n.rule('cc', '$cpp $cppflags -MD -MF $out.d -MT $out $in -o $out.i && $cc $ccflags $out.i -o $out.s'
               ' && printf \'\\t.align\\t2, 0\\n\' >> $out.s && $as $asflags -o $out $out.s',
               description='CC $in', depfile='$out.d', deps='gcc')
        n.rule('ld', '$ld -T $ldscript --no-warn-rwx-segments -Map $map -o $out @$out.rsp $symbols',
               description='LD $out', rspfile='$out.rsp', rspfile_content='$in_newline')
        n.rule('objcopy', '$objcopy -O binary --gap-fill 0x00 --pad-to 0x%08X $in $out' % project.ROM_END,
               description='OBJCOPY $out')
        n.rule('verify', '$python tools/verify.py $in', description='VERIFY $in', pool='console')
        # The ByteMatch progress report: gzip -n keeps progress/report.json.gz byte-stable for the same report.
        n.rule('report', '$objdiff report generate -o $out && gzip -9nc $out > progress/report.json.gz',
               description='REPORT $out')
        n.newline()

        n.build(rel(manifest), 'disasm',
                implicit=['tools/disasm.py', 'tools/project.py', rel(project.LAYOUT), rel(project.SYMBOLS), rel(baserom)])
        n.build('build.ninja', 'configure', implicit_outputs=[rel(c_symbols), 'objdiff.json'],
                implicit=['tools/configure.py', 'tools/project.py', rel(manifest), rel(project.SOURCES),
                          rel(project.SYMBOLS)])
        n.newline()

        objs = []
        for kind, s in link:
            if kind == 'asm':
                o = rel(obj / Path(s).with_suffix('.o'))
                n.build(o, 'as', 'asm/' + s, order_only=rel(manifest))
            else:
                o = rel(obj / 'c' / Path(s).with_suffix('.o'))
                n.build(o, 'cc', s, implicit=rel(project.CC) if project.CC.is_relative_to(ROOT) else None)
            objs.append(o)
        n.newline()

        n.build(rel(elf), 'ld', objs, implicit=[rel(project.LD_SCRIPT), rel(c_symbols)],
                variables={'ldscript': rel(project.LD_SCRIPT), 'map': rel(project.MAP), 'symbols': rel(c_symbols)},
                implicit_outputs=rel(project.MAP))
        n.build(rel(rom), 'objcopy', rel(elf))
        n.build('verify', 'verify', rel(rom), implicit='tools/verify.py')
        # Target objects of functions the ROM now takes from C: built for the report only, never linked.
        targets = []
        for s in target_only:
            o = rel(obj / Path(s).with_suffix('.o'))
            n.build(o, 'as', 'asm/' + s, order_only=rel(manifest))
            targets.append(o)
        report = rel(project.BUILD / 'report.json')
        tool = [args.objdiff] if '/' in args.objdiff else []  # a bare name comes from PATH
        n.build(report, 'report', 'objdiff.json', implicit=objs + targets + tool,
                implicit_outputs='progress/report.json.gz')
        n.build('report', 'phony', report)
        n.default(rel(rom))
    n_c = sum(1 for k, _ in link if k == 'c')
    print(f'configure: wrote build.ninja ({len(link) - n_c} asm files, {n_c} C files)')


if __name__ == '__main__':
    main()
